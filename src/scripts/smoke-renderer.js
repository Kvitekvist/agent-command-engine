const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const assert = require('node:assert/strict')
app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'ace-renderer-smoke-')))
const timeout = setTimeout(() => { console.error('Renderer smoke timed out'); app.exit(1) }, 30000)
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1400, height: 900, webPreferences: {
    preload: path.join(__dirname, 'smoke-renderer-preload.js'), sandbox: true, contextIsolation: true, nodeIntegration: false,
  } })
  const evaluate = code => win.webContents.executeJavaScript(code)
  async function until(expression) {
    for (let i = 0; i < 100; i++) {
      if (await evaluate(expression)) return
      await new Promise(resolve => setTimeout(resolve, 50))
    }
    throw new Error('Missing renderer state: ' + expression)
  }
  const click = label => evaluate(`Array.from(document.querySelectorAll('button')).find(button => button.textContent.trim() === ${JSON.stringify(label)})?.click()`)
  try {
    await win.loadFile(process.env.ACE_RENDERER_ENTRY || path.join(__dirname, '../dist/renderer/index.html'))
    await until(`document.body.textContent.includes('Smoke project')`)
    await click('Smoke project')
    await click('Usage (whole machine)')
    await until(`smoke.pendingHistory(1)`)
    await click('Project 2')
    await until(`smoke.pendingHistory(2)`)
    const row = { client: 'claude', model: 'test-model', day: '2026-09-14', input: 10, output: 1, cost: 0, prompts: 1, agentName: 'Same name', sessionTitle: 'Same title' }
    const rows = [{ ...row, agentId: 'agent-two-a', sessionId: 'session-two-a' }, { ...row, agentId: 'agent-two-b', sessionId: 'session-two-b' }]
    await evaluate(`smoke.resolveHistory(2, ${JSON.stringify(rows)})`)
    await click('By Agent')
    await until(`document.querySelectorAll('tbody tr').length === 2`)
    await evaluate(`smoke.resolveHistory(1, ${JSON.stringify([{ ...row, agentId: 'stale-agent', agentName: 'STALE', sessionId: 'stale-session' }])})`)
    await new Promise(resolve => setTimeout(resolve, 100))
    assert.equal(await evaluate(`document.body.textContent.includes('STALE')`), false)
    assert.equal(await evaluate(`document.querySelectorAll('tbody tr').length`), 2)
    await click('By Session')
    await until(`document.querySelectorAll('tbody tr').length === 2`)
    assert.equal(await evaluate(`document.body.textContent.includes('session-two-a') && document.body.textContent.includes('session-two-b')`), true)
    await evaluate(`Array.from(document.querySelectorAll('button')).filter(button => button.textContent.includes('Refresh')).at(-1).click()`)
    await until(`smoke.pendingHistory(2)`)
    await evaluate(`document.querySelector('[aria-label="Remove Project 2"]').click()`)
    await until(`document.body.textContent.includes('Remove Project 2?')`)
    await click('Remove project')
    await until(`document.body.textContent.includes('Select a project to see its history.')`)
    await evaluate(`smoke.resolveHistory(2, ${JSON.stringify(rows)})`)
    await new Promise(resolve => setTimeout(resolve, 100))
    assert.equal(await evaluate(`document.querySelectorAll('tbody tr').length`), 0)
    await click('Smoke project')
    await click('Project Notes')
    await until(`!!document.querySelector('[role="dialog"] textarea')`)
    assert.equal(await evaluate(`document.querySelector('#root').inert`), true)
    await evaluate(`(() => { const input = document.querySelector('textarea'); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(input, 'smoke note'); input.dispatchEvent(new Event('input', { bubbles: true })); })()`)
    await until(`!Array.from(document.querySelectorAll('button')).find(b => b.textContent === 'Add note').disabled`)
    await click('Add note')
    await until(`!!document.querySelector('pre') && document.querySelector('pre').textContent === 'smoke note'`)
    if (process.env.ACE_SMOKE_SCREENSHOT_DIR) {
      for (const [width, height, zoom] of [[1400, 900, 1], [800, 600, 2]]) {
        win.setSize(width, height)
        win.webContents.setZoomFactor(zoom)
        await new Promise(resolve => setTimeout(resolve, 150))
        const shot = await win.webContents.capturePage()
        fs.writeFileSync(path.join(process.env.ACE_SMOKE_SCREENSHOT_DIR, `notes-${width}-${zoom}x.png`), shot.toPNG())
      }
      win.setSize(1400, 900)
      win.webContents.setZoomFactor(1)
    }
    const draft = text => evaluate(`(() => { const input = document.querySelector('textarea'); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(input, ${JSON.stringify(text)}); input.dispatchEvent(new Event('input', { bubbles: true })); })()`)
    await draft('failed draft')
    await click('Add note')
    await until(`document.body.textContent.includes('Simulated read-only notes file')`)
    assert.equal(await evaluate(`document.querySelector('textarea').value`), 'failed draft')
    assert.equal(await evaluate(`document.querySelector('pre').textContent`), 'smoke note')
    await draft('delayed draft')
    await click('Add note')
    await until(`document.querySelector('textarea').disabled`)
    assert.equal(await evaluate(`document.querySelector('textarea').value`), 'delayed draft')
    await until(`document.querySelector('textarea').value === ''`)
    await evaluate(`document.querySelector('[aria-label="Close dialog"]').click()`)
    await until(`!document.querySelector('[role="dialog"]')`)
    assert.equal(await evaluate(`document.querySelector('#root').inert`), false)
    await click('Settings')
    await until(`document.body.textContent.includes('Default Provider & Model')`)
    await evaluate(`Array.from(document.querySelectorAll('button')).find(button => button.getClientRects().length && button.textContent.endsWith('Codex'))?.click()`)
    await click('Save Settings')
    await until(`document.body.textContent.includes('Saved')`)
    await click('Agents')
    await until(`document.querySelector('select[aria-label="Model"]').value === 'gpt-5.6-terra'`)
    await click('Settings')
    await click('Models')
    await until(`document.querySelectorAll('input[type="checkbox"]:checked').length > 0`)
    await evaluate(`document.querySelectorAll('input[type="checkbox"]:checked').forEach(input => input.click())`)
    await click('Save Model Visibility')
    await click('Agents')
    await until(`document.querySelector('select[aria-label="Model"]').disabled`)
    assert.equal(await evaluate(`Array.from(document.querySelectorAll('button')).find(button => button.textContent === '+ New Agent').disabled`), true)
    await evaluate(`document.querySelector('button[title="sample.js"]').click()`)
    await until(`!!document.querySelector('.monaco-editor')`)
    await until(`!!document.querySelector('.monaco-editor textarea')`)
    await until(`document.querySelector('.monaco-editor .view-lines')?.textContent.includes('sample')`)
    win.webContents.focus()
    await evaluate(`document.querySelector('.monaco-editor textarea').focus()`)
    win.webContents.insertText('unsaved text')
    await until(`document.body.textContent.includes('Unsaved')`)
    await evaluate(`smoke.requestClose()`)
    await until(`document.body.textContent.includes('Save changes before closing?')`)
    await click('Cancel')
    assert.equal(await evaluate(`smoke.closeDecision()`), false)
    await evaluate(`smoke.failSave(true); smoke.requestClose()`)
    await click('Save all')
    await until(`document.body.textContent.includes('Simulated editor save failure')`)
    assert.equal(await evaluate(`smoke.closeDecision()`), null)
    assert.equal(await evaluate(`document.body.textContent.includes('Unsaved')`), true)
    await evaluate(`smoke.failSave(false)`)
    await click('Save all')
    await until(`smoke.closeDecision() === true`)
    await evaluate(`(() => { const row = document.querySelector('button[title="sample.js"]'); row.focus(); row.dispatchEvent(new KeyboardEvent('keydown', { key: 'F10', shiftKey: true, bubbles: true })); })()`)
    await until(`!!document.querySelector('[role="menu"]')`)
    await evaluate(`Array.from(document.querySelectorAll('[role="menuitem"]')).find(button => button.textContent.startsWith('Rename'))?.click()`)
    await until(`!!document.querySelector('input[aria-label="New name"]')`)
    await click('Cancel')
    await until(`!document.querySelector('[role="dialog"]')`)
    assert.equal(await evaluate(`document.activeElement.title`), 'sample.js')
    await evaluate(`Promise.all(['editorWorkerService', 'json', 'css', 'html', 'typescript'].map(label => new Promise((resolve, reject) => {
      const worker = globalThis.MonacoEnvironment.getWorker('', label);
      worker.onerror = event => { worker.terminate(); reject(new Error(event.message || 'Worker failed')); };
      setTimeout(() => { worker.terminate(); resolve(); }, 500);
    })))`)
    console.log('Built renderer: Notes failure/delay, history races/identities, live settings, close guards, keyboard rename and offline Monaco workers passed')
    clearTimeout(timeout)
    win.destroy()
    app.exit(0)
  } catch (error) {
    console.error(error.stack)
    clearTimeout(timeout)
    app.exit(1)
  }
})
